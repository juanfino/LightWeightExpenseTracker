def _to_art(created_at: str) -> str:
    """Convert a stored UTC timestamp string to an ART date/time string for display."""
    try:
        dt = datetime.strptime(created_at, "%Y-%m-%d %H:%M:%S").replace(tzinfo=timezone.utc)
        return dt.astimezone(BAIRES).strftime("%Y-%m-%d %H:%M")
    except (ValueError, TypeError):
        return str(created_at)


# ── Result helpers ────────────────────────────────────────────────────────────

def _reply(text: str) -> dict:
    return {"kind": "reply", "text": text}


def _first_tool_use(message):
    for block in message.content:
        if getattr(block, "type", None) == "tool_use":
            return block
    return None


def _joined_text(message) -> str:
    parts = [getattr(b, "text", "") for b in message.content if getattr(b, "type", None) == "text"]
    return "\n".join(p for p in parts if p).strip()


def _extract_ids(rows: list[dict]) -> list[int]:
    ids = []
    for r in rows:
        val = r.get("id") if "id" in r else (next(iter(r.values()), None) if r else None)
        try:
            ids.append(int(val))
        except (TypeError, ValueError):
            continue
    return ids


# ── Entry point ───────────────────────────────────────────────────────────────

def route_intent(text: str, user, anthropic_api_key: str, history: list | None = None) -> dict:
    """Classify and act on a free-text message. Returns a dict with a 'kind':
      - {"kind":"log", "concept","amount","date","category","subcategory"}
      - {"kind":"edit", "candidate_ids":[int], "changes":{...}}
      - {"kind":"category", "name"}
      - {"kind":"subcategory", "parent","name"}
      - {"kind":"report", "text"}   (Spanish reply already composed)
      - {"kind":"reply", "text"}    (clarification / free text)
      - {"kind":"error", "text"}

    ``history`` is an optional list of prior {"role": "user"/"assistant", "content": str}
    turns (a short rolling window kept by the caller) prepended before the current
    message, so the model can resolve short-lived follow-ups ("dame el desglose",
    "sí, por persona") within that window. Performs no Telegram I/O; the bot turns
    the result into messages/confirmation flows.
    """
    try:
        client = anthropic.Anthropic(api_key=anthropic_api_key, timeout=20.0, max_retries=0)
        system = _build_system_prompt(user)
    except Exception as e:
        logger.error("Error preparando intent layer: %s", e)
        return {"kind": "error", "text": "⚠️ No pude procesar el mensaje. Probá de nuevo."}

    messages = [{"role": h["role"], "content": h["content"]} for h in (history or [])]
    messages.append({"role": "user", "content": text})

    try:
        for _ in range(_MAX_TOOL_TURNS):
            call_started = llm_usage.started()
            try:
                message = client.messages.create(
                    model=_MODEL,
                    max_tokens=1024,
                    system=system,
                    tools=_TOOLS,
                    messages=messages,
                )
            except Exception as e:
                llm_usage.record("intent", _MODEL, call_started, error=e)
                raise
            llm_usage.record("intent", _MODEL, call_started, response=message)

            tool = _first_tool_use(message)
            if tool is None:
                # No tool call: treat any text as a direct reply.
                reply = _joined_text(message)
                return _reply(reply or "🤔 No te entendí. ¿Podés reformularlo?")

            name = tool.name
            args = tool.input or {}

            if name == "log_expense":
                return _handle_log(args)
            if name == "edit_expense":
                return _handle_edit(args, user)
            if name == "create_category":
                return _handle_create_category(args)
            if name == "create_subcategory":
                return _handle_create_subcategory(args)
            if name == "run_report":
                # Read-only loop: execute SELECT, feed rows back, let the model compose.
                tool_result = _run_report_sql(args.get("sql", ""))
                messages.append({"role": "assistant", "content": message.content})
                messages.append({
                    "role": "user",
                    "content": [{
                        "type": "tool_result",
                        "tool_use_id": tool.id,
                        "content": tool_result,
                    }],
                })
                continue

            # Unknown tool name — shouldn't happen.
            return _reply("🤔 No te entendí. ¿Podés reformularlo?")

        # Ran out of turns without a final answer.
        return _reply("🤔 No pude completar la consulta. ¿Podés reformularla?")
    except Exception as e:
        logger.error("Error en intent layer: %s", e)
        return {"kind": "error", "text": "⚠️ Hubo un error interpretando el mensaje. Probá de nuevo."}


def _handle_log(args: dict) -> dict:
    try:
        amount = float(args.get("amount"))
    except (TypeError, ValueError):
        return _reply("🤔 No me quedó claro el monto. ¿Me lo repetís?")
    if amount <= 0:
        return _reply("🤔 No me quedó claro el monto. ¿Me lo repetís?")
    concept = (args.get("concept") or "").strip()
    if not concept:
        return _reply("🤔 ¿Qué concepto le pongo al gasto?")
    return {
        "kind": "log",
        "concept": concept,
        "amount": amount,
        "currency": db.normalize_currency(args.get("currency")),
        "date": (args.get("date") or "").strip() or None,
        "category": (args.get("category") or "").strip() or None,
        "subcategory": (args.get("subcategory") or "").strip() or None,
    }


def _handle_edit(args: dict, user) -> dict:
    target_sql = args.get("target_sql", "")
    changes = args.get("changes") or {}
    # Normalize changes to a clean dict.
    clean: dict = {}
    if changes.get("amount") is not None:
        try:
            amt = float(changes["amount"])
            if amt > 0:
                clean["amount"] = amt
        except (TypeError, ValueError):
            pass
    if changes.get("currency") is not None:
        try:
            clean["currency"] = db.normalize_currency(changes["currency"])
        except ValueError:
            pass
    for key in ("concept", "category", "subcategory", "date", "fixed_expense"):
        val = changes.get(key)
        if isinstance(val, str) and val.strip():
            clean[key] = val.strip()
    if not clean:
        return _reply("🤔 No entendí qué querés cambiar del gasto.")

    try:
        rows = sqlro.run_readonly(target_sql, max_rows=25)
    except sqlro.ReadOnlySQLError as e:
        logger.warning("edit target_sql rechazado: %s | sql=%s", e, target_sql)
        return _reply("🤔 No pude identificar el gasto. ¿Podés ser más específico?")

    candidate_ids = _extract_ids(rows)
    return {"kind": "edit", "candidate_ids": candidate_ids, "changes": clean}


def _handle_create_category(args: dict) -> dict:
    name = (args.get("name") or "").strip()
    if not name:
        return _reply("🤔 ¿Qué nombre le pongo a la categoría?")
    return {"kind": "category", "name": name}


def _handle_create_subcategory(args: dict) -> dict:
    name = (args.get("name") or "").strip()
    parent = (args.get("parent_category") or "").strip()
    if not name or not parent:
        return _reply("🤔 Decime la categoría madre y el nombre de la subcategoría.")
    return {"kind": "subcategory", "parent": parent, "name": name}


def _run_report_sql(sql: str) -> str:
    """Execute a report SELECT under guardrails and return a compact JSON string
    (rows or error) to feed back to the model as a tool_result."""
    try:
        rows = sqlro.run_readonly(sql, max_rows=200)
    except sqlro.ReadOnlySQLError as e:
        return json.dumps({"error": str(e)}, ensure_ascii=False)
    return json.dumps({"rows": rows}, ensure_ascii=False, default=str)
