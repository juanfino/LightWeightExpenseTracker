"""Natural-language intent layer for the Telegram bot.

Generic text that the deterministic parser shouldn't handle (edits, taxonomy
management, reports, richer phrasings) is routed here. We use the Anthropic model
already used elsewhere in the project (Haiku) with **tool use / function calling**
— the first such usage in the codebase.

Design:
- A single round trip classifies the message and maps names -> ids: the current
  taxonomy, the requesting user's recent expenses, the ART date and the DB schema
  are injected up front so the model can resolve references like "el último de
  verdulería" and pick category/concept filters in one shot.
- MUTATIONS (log/edit expense, create category/subcategory) are returned as
  structured params; the bot confirms (edits/taxonomy) or auto-saves (logging)
  and executes the write with parameterized application code. The model NEVER
  writes the mutation itself.
- READS (reports and edit-targeting) are SELECTs generated by the model and
  executed through ``sqlro.run_readonly`` (SELECT-only, read-only connection,
  statement timeout). For reports we feed rows back as a tool_result so the model
  composes a natural Spanish reply.

``route_intent`` returns a dict describing the outcome; the bot turns that into
messages / inline-confirmation flows. It performs no Telegram I/O itself.
"""

